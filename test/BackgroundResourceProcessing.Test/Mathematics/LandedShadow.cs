using System;
using BackgroundResourceProcessing.Shadow;
using KSP.Testing;

namespace BackgroundResourceProcessing.Test.Mathematics;

public sealed class LandedShadowTests : BRPTestBase
{
    // Points within this much of the terminator (|lit-dot|) are skipped so that
    // floating point noise right at sunrise/sunset cannot make the test flaky.
    const double TerminatorMargin = 0.1;

    // Likewise for points within this many metres of the edge of the shadow of
    // a body that the planet orbits.
    const double AncestorMargin = 1000.0;

    // Ground-truth snapshot fixture. Each SAMPLE records the true lit/shadow
    // state of a surface point at a fixed UT, computed in Unity world space from
    // KSP's own orbit/rotation math (getTruePositionAtUT + PlanetaryFrame). It is
    // regenerated by the snapshot generator (see the repo's shadow snapshot cfg).
    static readonly string SnapshotPath = System.IO.Path.Combine(
        KSPUtil.ApplicationRootPath,
        "GameData/BackgroundResourceProcessing.Test/PluginData/vessels/shadow/lit-state-snapshot.cfg"
    );

    /// <summary>
    /// A vessel landed on the sunlit side of a body must be reported as lit, and
    /// one on the night side must be reported as in shadow.
    /// </summary>
    ///
    /// <remarks>
    /// Regression test for issue #26. The landed shadow code dotted a surface
    /// normal (Unity world space, from <see cref="CelestialBody.GetSurfaceNVector"/>)
    /// against orbital sun positions reconstructed in KSP's internal orbit frame.
    /// The frame mismatch inverted the lit/shadow result, so unloaded solar
    /// vessels would not begin charging after sunrise.
    ///
    /// Ground truth comes from a pre-built snapshot rather than the live scene.
    /// <see cref="CelestialBody.position"/> and <see cref="CelestialBody.GetSurfaceNVector"/>
    /// are only valid in scenes that keep every body's world transform up to date
    /// (a flight scene); the main menu only updates the menu bodies, so reading
    /// them there yields stale garbage and nothing can be checked. The snapshot
    /// bakes the world-space truth (computed once, the same way the terminator
    /// test's <see cref="TruthLitDot"/> does) so the assertion runs in any scene,
    /// including the main menu where the in-game test runner lives.
    /// </remarks>
    [TestInfo("LandedShadowTests_TestLitStateMatchesGroundTruth")]
    public void TestLitStateMatchesGroundTruth()
    {
        var sun = Planetarium.fetch?.Sun;
        var bodies = FlightGlobals.Bodies;
        if (sun == null || bodies == null || bodies.Count == 0)
        {
            // Celestial bodies aren't loaded (e.g. the test is being run outside
            // of a game scene). There's nothing we can check.
            return;
        }

        var snapshot = ConfigNode.Load(SnapshotPath)?.GetNode("LIT_STATE_SNAPSHOT");
        Assert.IsTrue(
            snapshot != null,
            $"lit-state snapshot fixture missing or unreadable at {SnapshotPath}"
        );

        double UT = 0.0;
        Assert.IsTrue(snapshot.TryGetValue("UT", ref UT), "snapshot has no UT");

        int chec_ed = 0;

        foreach (var bodyNode in snapshot.GetNodes("BODY"))
        {
            var name = bodyNode.GetValue("name");
            var planet = FindBody(bodies, name);
            if (planet == null)
                continue;

            // The oracle was baked for one system geometry. Only check bodies
            // whose live orbit still matches the snapshot's recorded heliocentric
            // position, so a planet pack that has moved a body is skipped rather
            // than reported as a false failure. The snapshot's stock bodies match
            // any install that leaves the stock system intact.
            Vector3d snapHelio = default;
            if (!bodyNode.TryGetValue("helio", ref snapHelio))
                continue;
            Vector3d liveHelio = planet.getTruePositionAtUT(UT) - sun.getTruePositionAtUT(UT);
            if ((liveHelio - snapHelio).magnitude > 1e-3 * snapHelio.magnitude)
                continue;

            foreach (var sampleNode in bodyNode.GetNodes("SAMPLE"))
            {
                double lat = 0.0,
                    lon = 0.0,
                    litDot = 0.0;
                bool expectedInShadow = false;
                sampleNode.TryGetValue("lat", ref lat);
                sampleNode.TryGetValue("lon", ref lon);
                sampleNode.TryGetValue("litDot", ref litDot);
                sampleNode.TryGetValue("inShadow", ref expectedInShadow);

                // Skip points sitting right on the terminator; the lit/shadow sign
                // there is floating-point noise and would make the test flaky.
                if (Math.Abs(litDot) < TerminatorMargin)
                    continue;

                // The snapshot only records the planet's own shadow. The
                // shadows of the bodies the planet orbits (such as Jool's on
                // Laythe) come from orbit positions, which are valid in any
                // scene, so they are checked live.
                var ancestor = TruthAncestorMargin(planet, sun, lat, lon, UT);
                if (Math.Abs(ancestor) < AncestorMargin)
                    continue;
                if (ancestor < 0.0)
                    expectedInShadow = true;

                var state = ShadowState.ComputeLandedShadowState(planet, sun, lat, lon, UT);

                Assert.AreEqual(
                    expectedInShadow,
                    state.InShadow,
                    $"{name} @ lat={lat} lon={lon}: "
                        + $"BRP reported InShadow={state.InShadow} but the snapshot says the "
                        + $"surface is {(expectedInShadow ? "in shadow" : "lit")} (lit-dot={litDot:F3})"
                );

                chec_ed += 1;
            }
        }

        Assert.IsTrue(
            chec_ed > 0,
            "No landed shadow points were checked; none of the snapshot's bodies are "
                + "present in this save's system. Regenerate the lit-state snapshot."
        );
    }

    /// <summary>
    /// Find a celestial body by name, avoiding LINQ (BRP ships its own ambiguous
    /// <c>Select</c> extension).
    /// </summary>
    private static CelestialBody FindBody(
        System.Collections.Generic.List<CelestialBody> bodies,
        string name
    )
    {
        foreach (var body in bodies)
        {
            if (body.bodyName == name)
                return body;
        }
        return null;
    }

    /// <summary>
    /// The predicted time of the next terminator for a landed vessel must match
    /// the time the surface actually crosses into/out of sunlight.
    /// </summary>
    ///
    /// <remarks>
    /// Regression test for the landed shadow rotation-direction bug.
    /// <c>LandedShadow.ComputeDotAt</c> spun the surface normal about the body's
    /// rotation axis in the wrong direction (KSP's true angular velocity points
    /// along <c>-RotationAxis</c>), so the lit/shadow state at the current
    /// instant could be correct while the predicted terminator landed on the
    /// wrong side of the day, desynchronising the day/night cycle.
    ///
    /// Ground truth is produced by walking the body's true rotation forward in
    /// time using KSP's own rotation formulas (<see cref="Planetarium.CelestialFrame.PlanetaryFrame"/>
    /// plus <see cref="CelestialBody.getTruePositionAtUT"/>) and finding when the
    /// real surface normal crosses the terminator.
    /// </remarks>
    [TestInfo("LandedShadowTests_TestTerminatorMatchesGroundTruth")]
    public void TestTerminatorMatchesGroundTruth()
    {
        var sun = Planetarium.fetch?.Sun;
        var bodies = FlightGlobals.Bodies;
        if (sun == null || bodies == null || bodies.Count == 0)
            return;

        double now = Planetarium.GetUniversalTime();
        const double lat = 12.0;
        const double lon = 47.0;
        int chec_ed = 0;

        foreach (var planet in bodies)
        {
            if (planet.isStar || planet.referenceBody == null || !planet.rotates)
                continue;
            if (planet.rotationPeriod == 0.0)
                continue;
            // Nothing can land on the invisible barycentre of a binary system,
            // and the other bodies orbiting it, which shadow it, aren't
            // modelled by the ground truth here.
            if (!ShadowState.StarProvider.BlocksLight(planet))
                continue;

            // Skip points sitting right on the terminator; the predicted crossing
            // is ill-conditioned there and the assertion would be noisy.
            if (Math.Abs(TruthLitDot(planet, sun, lat, lon, now)) < TerminatorMargin)
                continue;
            if (Math.Abs(TruthAncestorMargin(planet, sun, lat, lon, now)) < AncestorMargin)
                continue;

            // We only need to search a little over one rotation to be guaranteed
            // a terminator (away from the poles).
            // rotationPeriod is negative for retrograde rotators.
            double span = Math.Abs(planet.rotationPeriod) * 1.5;
            double truthUT = FindTruthTerminator(planet, sun, lat, lon, now, span);
            if (truthUT < 0.0)
                continue;

            var state = ShadowState.ComputeLandedShadowState(planet, sun, lat, lon, now);
            double brpUT = state.NextTerminatorEstimate;
            if (double.IsInfinity(brpUT) || double.IsNaN(brpUT))
                continue;

            // The terminator can legitimately be far in the future for slow
            // rotators, so allow a small relative slack on top of an absolute
            // floor. The bug shifts the terminator by a large fraction of a day,
            // far outside this tolerance.
            double tolerance = Math.Max(120.0, 0.01 * (truthUT - now));

            Assert.IsTrue(
                Math.Abs(brpUT - truthUT) <= tolerance,
                $"{planet.bodyName} @ lat={lat} lon={lon}: BRP predicts the next "
                    + $"terminator at UT {brpUT:F1} (+{brpUT - now:F0}s) but it actually "
                    + $"occurs at UT {truthUT:F1} (+{truthUT - now:F0}s), "
                    + $"a difference of {brpUT - truthUT:F0}s."
            );

            chec_ed += 1;
        }

        Assert.IsTrue(
            chec_ed > 0,
            "No landed terminators were checked; celestial bodies may not be loaded."
        );
    }

    /// <summary>
    /// Reconstruct the real lit-dot (outward surface normal vs direction to the
    /// sun) at an arbitrary UT using KSP's own rotation model. Positive means
    /// lit. This is computed entirely in Unity world space and does not depend on
    /// any BRP math.
    /// </summary>
    private static double TruthLitDot(
        CelestialBody body,
        CelestialBody sun,
        double lat,
        double lon,
        double UT
    )
    {
        Vector3d normal = TruthNormal(body, lat, lon, UT);
        Vector3d toSun = sun.getTruePositionAtUT(UT) - body.getTruePositionAtUT(UT);

        return Vector3d.Dot(normal, toSun.normalized);
    }

    /// <summary>
    /// The outward surface normal in the same frame as
    /// <see cref="CelestialBody.getTruePositionAtUT"/>, from KSP's own rotation
    /// model.
    /// </summary>
    private static Vector3d TruthNormal(CelestialBody body, double lat, double lon, double UT)
    {
        double rotAngle = (body.initialRotation + 360.0 * body.rotPeriodRecip * UT) % 360.0;
        double directRot = (rotAngle - Planetarium.InverseRotAngle) % 360.0;

        Planetarium.CelestialFrame frame = default;
        Planetarium.CelestialFrame.PlanetaryFrame(0.0, 90.0, directRot, ref frame);

        Vector3d local = Planetarium.SphericalVector(lat * Math.PI / 180.0, lon * Math.PI / 180.0);
        return frame.LocalToWorld(local).xzy.normalized;
    }

    /// <summary>
    /// The smallest distance from the surface point to the edge of the shadow
    /// of a body that <paramref name="body"/> orbits (such as Jool for Laythe),
    /// which is negative inside one. Bodies that the star orbits, or that are
    /// the star, are left out. This is <see cref="double.PositiveInfinity"/>
    /// if there are no such bodies.
    /// </summary>
    private static double TruthAncestorMargin(
        CelestialBody body,
        CelestialBody sun,
        double lat,
        double lon,
        double UT
    )
    {
        var sunChain = new System.Collections.Generic.HashSet<CelestialBody>();
        for (var b = sun; b != null && sunChain.Add(b); b = b.orbit?.referenceBody) { }

        Vector3d sunPos = sun.getTruePositionAtUT(UT);
        Vector3d point =
            body.getTruePositionAtUT(UT) + body.Radius * TruthNormal(body, lat, lon, UT);

        double margin = double.PositiveInfinity;
        for (
            var ancestor = body.referenceBody;
            ancestor != null && !sunChain.Contains(ancestor);
            ancestor = ancestor.orbit?.referenceBody
        )
        {
            Vector3d pos = ancestor.getTruePositionAtUT(UT);
            Vector3d sunV = pos - sunPos;
            double D = sunV.magnitude;
            Vector3d dir = sunV / D;
            Vector3d v = point - pos;

            double x = Vector3d.Dot(dir, v);
            double m =
                x <= 0.0
                    ? v.magnitude - ancestor.Radius
                    : (v - x * dir).magnitude - ancestor.Radius * (1.0 + x / D);
            margin = Math.Min(margin, m);
        }

        return margin;
    }

    /// <summary>
    /// Whether the surface point is in shadow, either because it is on the
    /// night side or because it is in the shadow of a body that its planet
    /// orbits.
    /// </summary>
    private static bool TruthInShadow(
        CelestialBody body,
        CelestialBody sun,
        double lat,
        double lon,
        double UT
    ) =>
        TruthLitDot(body, sun, lat, lon, UT) <= 0.0
        || TruthAncestorMargin(body, sun, lat, lon, UT) <= 0.0;

    /// <summary>
    /// Find the UT of the next terminator crossing after <paramref name="now"/>,
    /// or a negative value if none is found within <paramref name="span"/>.
    /// </summary>
    private static double FindTruthTerminator(
        CelestialBody body,
        CelestialBody sun,
        double lat,
        double lon,
        double now,
        double span
    )
    {
        const int Steps = 2000;
        double step = span / Steps;
        bool prev = TruthInShadow(body, sun, lat, lon, now);

        for (double t = now + step; t <= now + span; t += step)
        {
            bool cur = TruthInShadow(body, sun, lat, lon, t);
            if (prev != cur)
            {
                double lo = t - step;
                double hi = t;
                for (int i = 0; i < 48; ++i)
                {
                    double mid = 0.5 * (lo + hi);
                    bool loLit = TruthInShadow(body, sun, lat, lon, lo);
                    bool midLit = TruthInShadow(body, sun, lat, lon, mid);
                    if (loLit == midLit)
                        lo = mid;
                    else
                        hi = mid;
                }
                return 0.5 * (lo + hi);
            }
            prev = cur;
        }

        return -1.0;
    }
}
